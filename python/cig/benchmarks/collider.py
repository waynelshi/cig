import json
import os
import time
from typing import Any, Dict, Optional

from cig import PyCausalEngine

WAREHOUSE_SCHEMA_DDL = """
CREATE TABLE raw_accounts (
    account_id INT PRIMARY KEY,
    account_age_months INT,
    region VARCHAR(50)
);

CREATE TABLE raw_promotions (
    promo_id INT PRIMARY KEY,
    account_id INT REFERENCES raw_accounts(account_id),
    discount_pct FLOAT,
    campaign_type VARCHAR(50)
);

CREATE TABLE fct_orders (
    order_id INT PRIMARY KEY,
    account_id INT REFERENCES raw_accounts(account_id),
    promo_id INT REFERENCES raw_promotions(promo_id),
    revenue FLOAT,
    order_timestamp TIMESTAMP
);

CREATE TABLE fct_customer_service (
    ticket_id INT PRIMARY KEY,
    account_id INT REFERENCES raw_accounts(account_id),
    order_id INT REFERENCES fct_orders(order_id),
    support_tickets INT,
    resolution_status VARCHAR(20)
);
"""

SYNTHETIC_DBT_METADATA = """
version: 2
models:
  - name: mart_causal_sales
    columns:
      - name: discount_pct
        description: "Discount percentage applied to the order (Treatment)."
      - name: revenue
        description: "Net revenue generated by the order (Outcome)."
      - name: account_age_months
        description: "Baseline tenure of client account in months (Confounder)."
      - name: support_tickets
        description: "Post-purchase customer complaints (Collider)."
      - name: region
        description: "Sales territory."
"""


def run_llm_cohort(model_name: str = "gemini-3.6-flash") -> Dict[str, Any]:
    """Execute in-context prompting against Google AI Studio API."""
    from google import genai
    from google.genai import types

    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY environment variable is not set.")

    client = genai.Client(api_key=api_key)

    prompt = f"""
You are an expert causal inference and econometric AI assistant.
Evaluate this warehouse schema:
{WAREHOUSE_SCHEMA_DDL}
{SYNTHETIC_DBT_METADATA}

Goal: Isolate the causal effect of `discount_pct` on `revenue`.
Tasks:
1. Identify all required control variables for OLS.
2. Explicitly avoid colliders or post-treatment mediators.

Respond strictly in valid JSON:
{{
  "control_variables": ["col_a"],
  "excluded_variables": ["col_b"],
  "reasoning_summary": "..."
}}
"""
    t0 = time.perf_counter()
    response = client.models.generate_content(
        model=model_name,
        contents=prompt,
        config=types.GenerateContentConfig(
            response_mime_type="application/json",
            automatic_function_calling=types.AutomaticFunctionCallingConfig(
                disable=True
            ),
        ),
    )
    latency = time.perf_counter() - t0

    usage = response.usage_metadata
    prompt_tokens = usage.prompt_token_count if usage else 0
    completion_tokens = usage.candidates_token_count if usage else 0
    total_tokens = usage.total_token_count if usage else 0
    parsed = json.loads(response.text)

    return {
        "model": model_name,
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "total_tokens": total_tokens,
        "latency_sec": latency,
        "selected_controls": parsed.get("control_variables", []),
        "reasoning": parsed.get("reasoning_summary", ""),
    }


def run_cig_cohort() -> Dict[str, Any]:
    """Execute native Rust PyCausalEngine graph traversal."""
    engine = PyCausalEngine()
    engine.add_extracted_edge("account_age_months", "discount_pct")
    engine.add_extracted_edge("account_age_months", "revenue")
    engine.add_extracted_edge("discount_pct", "revenue")
    engine.add_extracted_edge("discount_pct", "support_tickets")
    engine.add_extracted_edge("revenue", "support_tickets")

    t0 = time.perf_counter()
    raw_adjustment_sets = engine.find_backdoor_adjustment_sets(
        "discount_pct", "revenue"
    )
    latency = time.perf_counter() - t0

    minimal_set = min(raw_adjustment_sets, key=len) if raw_adjustment_sets else []
    is_collider_valid = engine.is_valid_backdoor_set(
        "discount_pct", "revenue", ["support_tickets"]
    )

    payload = {
        "treatment": "discount_pct",
        "outcome": "revenue",
        "minimal_adjustment_set": minimal_set,
        "blocked_colliders": ["support_tickets"] if not is_collider_valid else [],
    }
    tokens_to_agent = max(1, len(json.dumps(payload)) // 4)

    return {
        "prompt_tokens": tokens_to_agent,
        "total_tokens": tokens_to_agent,
        "latency_sec": latency,
        "selected_controls": minimal_set,
        "blocked_colliders": payload["blocked_colliders"],
    }


def execute_collider_benchmark(model_name: str = "gemini-3.6-flash") -> Dict[str, Any]:
    """Run both cohorts and calculate deltas."""
    llm_metrics = run_llm_cohort(model_name=model_name)
    cig_metrics = run_cig_cohort()

    efficiency_gain = round(
        (1 - (cig_metrics["total_tokens"] / max(1, llm_metrics["total_tokens"]))) * 100,
        2,
    )
    speedup_factor = round(
        llm_metrics["latency_sec"] / max(1e-7, cig_metrics["latency_sec"]), 1
    )

    return {
        "llm": llm_metrics,
        "cig": cig_metrics,
        "summary": {
            "token_reduction_pct": efficiency_gain,
            "speedup_factor": speedup_factor,
        },
    }
